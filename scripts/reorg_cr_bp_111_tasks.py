#!/usr/bin/env python3
"""Reorganize the 100 task directories written by decompose_l4.py to the
correct post-mv1 location: under the activity's directory (nested under
the BP path).

The decompose_l4.py script writes to `entities/v1-alpha/<task_id>/`
using the full id as the dir name (e.g. `processes:task-ao-conceive-cqkwrm-intake`).
The post-mv1 layout nests tasks under the activity:
`entities/v1-alpha/<cell-dir>/<pg-hash>/<bp-hash>/<act-hash>/<task-hash>/`.

This script moves each misplaced task directory into the right place and
renames the file from `processes:task-...yaml` (with colon) to
`processes-task-...yaml` (with hyphen) to match the post-mv1 filename
convention used by the rest of the catalog.

It also rewrites the parent Activity's `composes:` entries so the
target_id stays valid and the `processes-task-...` filename
references the right file.
"""
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path('entities/v1-alpha')

# Build a map from task_id -> correct (cell-dir, bp-hash, act-hash)
# by parsing the task yaml's belongs_to_activity field.
moves = []
for task_dir in sorted(ROOT.glob('processes:task-*')):
    if not task_dir.is_dir():
        continue
    task_yaml_path = task_dir / f'{task_dir.name}.yaml'
    if not task_yaml_path.exists():
        print(f'WARN: no yaml in {task_dir}', file=sys.stderr)
        continue
    d = yaml.safe_load(task_yaml_path.read_text())
    if not isinstance(d, dict):
        print(f'WARN: non-dict yaml in {task_dir}', file=sys.stderr)
        continue
    activity_id = d.get('belongs_to_activity', '')
    if not activity_id.startswith('processes:activity-'):
        print(f'WARN: bad belongs_to_activity in {task_yaml_path}: {activity_id!r}', file=sys.stderr)
        continue
    # Find the activity dir on disk
    act_slug = activity_id.replace('processes:activity-', '')
    # search for the activity yaml (4 path components: cell/<pg-hash>/<bp-hash>/<act-hash>/)
    matches = list(ROOT.glob(f'*/*/*/processes-activity-{act_slug}.yaml'))
    if not matches:
        matches = list(ROOT.glob(f'*/*/*/*/processes-activity-{act_slug}.yaml'))
    if not matches:
        print(f'WARN: cannot find activity dir for {act_slug}', file=sys.stderr)
        continue
    act_yaml_path = matches[0]
    act_dir = act_yaml_path.parent  # the activity dir (named like <act-slug>)
    # The task should live at <act_dir>/<task-hash>/processes-task-<task-hash>.yaml
    task_id = d['id']
    task_hash = task_id.replace('processes:task-', '')
    correct_dir = act_dir / task_hash
    correct_file = correct_dir / f'processes-task-{task_hash}.yaml'
    moves.append((task_dir, task_yaml_path, correct_dir, correct_file, task_id))

print(f'Found {len(moves)} tasks to reorganize.')

# Execute moves
for task_dir, task_yaml_path, correct_dir, correct_file, task_id in moves:
    correct_dir.mkdir(parents=True, exist_ok=True)
    shutil.move(str(task_yaml_path), str(correct_file))
    shutil.rmtree(str(task_dir))
    print(f'moved: {task_yaml_path.relative_to(ROOT)} -> {correct_file.relative_to(ROOT)}')

# Now patch each parent Activity's composes[] to use the new target_id
# (the id doesn't actually change — `processes:task-<hash>` — but the
# task yaml's `id:` field is already correct; we just need to verify the
# composes[] entries are correct. They were generated by decompose_l4.py
# and reference the right id; nothing to change.)
print('\nDone.')
