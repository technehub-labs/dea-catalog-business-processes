#!/usr/bin/env python3
"""build_manifest.py — CR-BP-30 (provenance principle): MANIFEST.md.

Walks the release output directory and emits MANIFEST.md with one row
per file: path, bytes, sha256, and the generating script (derived from
the filename map below; verbatim copies are marked as such).

Deterministic: sorted walk; the version label is caller-supplied.

Usage:
  python3 scripts/build_manifest.py --dir out/v0.5.0 --version v0.5.0
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

GENERATED_BY = {
    "process-map.html": "scripts/generate_process_map.py (CR-BP-30a)",
    "process-map-a3.png": "scripts/generate_process_map.py --png (CR-BP-30a)",
    "catalog.xlsx": "scripts/build_catalog_xlsx.py (CR-BP-30b)",
    "bpmn-library.bpmn": "scripts/build_bpmn_artifact.py (CR-BP-30c)",
    "RELEASE-NOTES.md": "scripts/build_release_notes.py (CR-BP-30d)",
    "decisions.md": "scripts/build_release_notes.py --decisions (CR-BP-30d)",
    "MANIFEST.md": "scripts/build_manifest.py",
}
COPIED_FROM = {
    "decisions/dispositions-register.yaml":
        "reconciliation/dispositions/register.yaml (verbatim; D4=A)",
}


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--dir", required=True, help="release output directory")
    ap.add_argument("--version", required=True)
    args = ap.parse_args(argv)

    root = Path(args.dir)
    if not root.is_dir():
        print(f"ERROR: {root} is not a directory")
        return 2

    files = sorted(p for p in root.rglob("*") if p.is_file() and p.name != "MANIFEST.md")
    lines = [f"# MANIFEST — {args.version}", "",
             "Per-file provenance for the release package (CR-BP-30 §2",
             "provenance principle): source on disk, generating script,",
             "bytes, sha256. The zip is self-auditable without external",
             "context.", "",
             "| File | Bytes | sha256 | Generated by |",
             "| :--- | ---: | :--- | :--- |"]
    for p in files:
        rel = p.relative_to(root).as_posix()
        by = GENERATED_BY.get(p.name) or COPIED_FROM.get(rel) or "verbatim copy (substrate)"
        lines.append(f"| {rel} | {p.stat().st_size} | {_sha256(p)} | {by} |")

    out = root / "MANIFEST.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"manifest: wrote {out} ({len(files)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
